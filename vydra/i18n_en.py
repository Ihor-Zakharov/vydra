_RU_UNITS = {"Б": "B", "КБ": "KB", "МБ": "MB", "ГБ": "GB", "ТБ": "TB"}


def _size(text: str) -> str:
    """«1,5 ГБ» → «1.5 GB»."""
    m = re.fullmatch(r"([\d.,]+)\s*(Б|КБ|МБ|ГБ|ТБ)", text.strip())
    return f"{m[1].replace(',', '.')} {_RU_UNITS[m[2]]}" if m else text
